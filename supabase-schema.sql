-- 1. Buat Tabel Produk
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  title text not null,
  category text not null default 'fashion',
  platform text not null default 'tokopedia',
  product_url text not null,
  secondary_platform text,
  secondary_url text,
  price numeric not null default 0,
  original_price numeric,
  rating numeric default 5.0,
  sold_count text default 'Curated',
  image text,
  description text,
  recommendation_reason text,
  badge_text text,
  is_featured boolean default false
);

-- 2. Aktifkan Row Level Security (RLS)
alter table public.products enable row level security;

-- 3. Kebijakan Izin (Policy): Pengunjung Umum Boleh Membaca Semua Produk (SELECT)
drop policy if exists "Public products are viewable by everyone" on public.products;
create policy "Public products are viewable by everyone"
  on public.products
  for select
  using ( true );

-- 4. Kebijakan Izin (Policy): Izin Menambah Produk (INSERT)
drop policy if exists "Enable insert for all users" on public.products;
create policy "Enable insert for all users"
  on public.products
  for insert
  with check ( true );

-- 5. Kebijakan Izin (Policy): Izin Memperbarui Produk (UPDATE)
drop policy if exists "Enable update for all users" on public.products;
create policy "Enable update for all users"
  on public.products
  for update
  using ( true );

-- 6. Kebijakan Izin (Policy): Izin Menghapus Produk (DELETE)
drop policy if exists "Enable delete for all users" on public.products;
create policy "Enable delete for all users"
  on public.products
  for delete
  using ( true );

-- 7. Aktifkan Realtime Replication (Opsional agar katalog auto-update langsung)
alter publication supabase_realtime add table public.products;

